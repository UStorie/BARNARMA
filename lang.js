(function () {
  const all = window.BARNSTUDIO_I18N;
  const keys = Object.keys(all);
  function read(){try{return localStorage.getItem('barnstudio-language')==='en'?'en':'fr';}catch{return 'fr';}}
  function setLang(lang){
    if (lang !== 'en' && lang !== 'fr') lang='fr';
    document.documentElement.lang=lang;
    for (const el of document.querySelectorAll('[data-i18n]')) {
      const item=all[el.dataset.i18n];
      if(item) el.textContent=item[lang]||item.fr;
    }
    document.querySelectorAll('[data-language]').forEach(b=>b.setAttribute('aria-pressed',String(b.dataset.language===lang)));
    try{localStorage.setItem('barnstudio-language',lang);}catch{}
    window.dispatchEvent(new CustomEvent('barnstudio-language-change',{detail:{lang}}));
  }
  window.BARNSTUDIO_LANG={setLang, read};
  document.querySelectorAll('[data-language]').forEach(b=>b.addEventListener('click',()=>setLang(b.dataset.language)));
  setLang(read());
})();
